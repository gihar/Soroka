"""Показывать ли карточку сопоставления этому пользователю.

ADR-0002 решил показывать её при любом числе спикеров: покрытие именования
важнее мгновенности быстрого пути. Решение остаётся в силе — но у того, кто
проводит пять встреч в неделю и каждый раз жмёт «Пропустить», должен быть
способ сказать это один раз, а не пять.

Настройка пользователя перекрывает глобальный флаг администратора; ``None``
означает «не трогали, как решил администратор».
"""

from typing import Any, Optional


def should_confirm_mapping(user: Optional[Any], *, global_default: bool) -> bool:
    """Решить, показывать ли карточку: настройка пользователя, иначе глобальный флаг.

    Пользователя может не быть (не нашли запись) или у него может не быть поля
    (старая строка до миграции) — оба случая означают «как у всех», а не сбой.
    SQLite хранит флаг как 0/1, поэтому сравнение идёт по истинности, а не по
    ``is True``.
    """
    preference = getattr(user, "speaker_mapping_enabled", None) if user else None
    if preference is None:
        return global_default
    return bool(preference)
