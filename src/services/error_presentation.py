"""Как сбой обработки выглядит для пользователя.

Один источник правды для признака «кончились кредиты LLM» (HTTP 402) и текста,
которым о сбое сообщает путь возобновления после подтверждения сопоставления.

Раньше правила жили только в воркере очереди, а возобновление отправляло
``str(error)`` как есть — то есть сырой ответ провайдера. На проде 22.07.2026 это
означало payload OpenRouter с ``user_id`` и ``max_tokens`` прямо в чат, да ещё с
советом «начните обработку заново», бесполезным при кончившихся кредитах.

Текст сырой ошибки пользователю не показывается вовсе: к моменту возобновления
запись уже расшифрована, так что осмысленных для человека классов сбоя всего два
(кончились ресурсы / временный сбой API), а внутренности провайдера ему ничего не
объясняют — их место в логах, где теперь есть и traceback.

Голос — канон «что + шаг»: первая строка про то, что случилось, вторая про
следующий шаг. Без разметки: путь возобновления отправляет текст без
``parse_mode``, поэтому звёздочки и теги показались бы буквально.
"""


def is_insufficient_credits(error_text: str) -> bool:
    """Признак ошибки «закончились кредиты на LLM» (HTTP 402).

    Срабатывает и на типизированном ``LLMInsufficientCreditsError`` (русское
    «кредит»), и на сыром ответе провайдера (англ. «credits» / «402»).
    Регистр входа не важен.
    """
    lowered = (error_text or "").lower()
    return (
        "кредит" in lowered
        or "credit" in lowered
        or "error code: 402" in lowered
    )


# Слова, которыми исчерпание квоты подписки называет себя в тексте ошибки: своё
# у каждого провайдера плюс русское — у типизированного LLMQuotaExhaustedError.
# Таблица одна на оба пути опознания: сюда за ней ходит и граница клиента модели
# (``src.llm.protocol_generator``, где к маркеру добавляется HTTP-код и рождается
# типизированная ошибка), и всё, что ниже по течению работает с одним текстом.
# Второй копии тут не место: она уже расходилась, и нетипизированный сбой «out of
# quota» уезжал мимо квотной ветки — админ не получал ни квотного совета, ни
# вообще уведомления.
QUOTA_EXHAUSTION_MARKERS = (
    "квота подписки",
    "insufficient_quota",
    "insufficient quota",
    "allocationquota",
    "allocated quota",
    "quota exceeded",
    "exceeded your current quota",
    "quota_exhausted",
    "out of quota",
)


def is_quota_exhausted(error_text: str) -> bool:
    """Признак ошибки «исчерпана квота подписки».

    Срабатывает и на типизированном ``LLMQuotaExhaustedError`` (русская «квота
    подписки»), и на сыром ответе провайдера. Классификация по HTTP-коду живёт
    на границе клиента модели (``protocol_generator``) — там она поднимает
    типизированную ошибку; здесь тот же случай опознаётся ниже по течению, где
    от исключения остался один текст. Слова признака у обоих общие —
    :data:`QUOTA_EXHAUSTION_MARKERS`.

    Отличать от кредитов обязательно: «пополните баланс» на исчерпанной квоте —
    совет в пустоту (CONTEXT.md).
    """
    lowered = (error_text or "").lower()
    return any(marker in lowered for marker in QUOTA_EXHAUSTION_MARKERS)


def is_transient_api_error(error_text: str) -> bool:
    """Признак временного сбоя внешнего API — повтор через пару минут осмыслен."""
    lowered = (error_text or "").lower()
    return any(
        pattern in lowered
        for pattern in (
            'rate limit', 'quota', 'service unavailable',
            'connection', 'timeout', 'network',
        )
    )


def is_memory_pressure(error_text: str) -> bool:
    """Признак нехватки памяти на сервере — виноват не файл, а нагрузка.

    Ищем по основе «памят», а не по слову «память»: прод-текст говорит
    «использование памяти», и точное совпадение слова его не ловило — сбой
    уходил в общую ветку, а пользователь получал совет, который не помогал.
    """
    lowered = (error_text or "").lower()
    return any(
        pattern in lowered
        for pattern in ('памят', 'memory', 'перегруж', 'oom')
    )


def is_file_too_large(error_text: str) -> bool:
    """Признак превышения допустимого размера — лечится сжатием, не повтором."""
    lowered = (error_text or "").lower()
    return 'слишком большой' in lowered or 'too large' in lowered


def is_unsupported_media(error_text: str) -> bool:
    """Признак нечитаемой записи: битый контейнер или неподдерживаемый кодек.

    Отсутствие ffmpeg сюда не относится — это сбой окружения, а не файла.
    """
    lowered = (error_text or "").lower()
    return any(
        pattern in lowered
        for pattern in (
            'corrupt', 'unsupported data', 'invalid data',
            'moov atom', 'failed to load audio', 'failed to process audio',
            'неподдерживаемый формат', 'повреждён', 'повреждена',
        )
    )


def processing_failure_step(error_text: str) -> str:
    """Следующий шаг для пользователя, соответствующий причине сбоя.

    Порядок веток — от «виноваты мы» к «виноват файл»: сбой на нашей стороне
    важнее сообщить честно, потому что там повтор не помогает и совет
    «отправьте ещё раз» превращается в замкнутый круг (прод 30.07: 27 отказов
    подряд с обещанием, что повтор поможет).

    Квота — раньше всех: её текст содержит слово «quota», на которое отзывается
    ветка временного сбоя, а обещать «через несколько минут» здесь нельзя —
    период подписки минутами не измеряется.
    """
    if is_quota_exhausted(error_text):
        return (
            "Это ограничение на нашей стороне, файл менять не нужно — "
            "отправьте запись позже."
        )

    if is_insufficient_credits(error_text):
        return (
            "Это временная проблема на нашей стороне, файл менять не нужно — "
            "отправьте запись снова позже."
        )

    if is_memory_pressure(error_text):
        return (
            "Сервис перегружен — это на нашей стороне, с файлом всё в порядке. "
            "Отправьте запись через несколько минут."
        )

    if is_transient_api_error(error_text):
        return "Похоже на временный сбой сервиса — попробуйте через несколько минут."

    if is_file_too_large(error_text):
        return "Запись слишком большая — сожмите её или разделите на части."

    if is_unsupported_media(error_text):
        return (
            "Не удалось прочитать запись — пришлите её в другом формате "
            "(MP3, MP4 или WAV) или запишите заново."
        )

    return "Отправьте запись ещё раз — обычно повторная попытка помогает."


def processing_failure_message(stage_name: str, error_text: str) -> str:
    """Текст трекера о сбое: что случилось + шаг, зависящий от причины.

    Сырой текст исключения сюда не попадает — он остаётся в логах; наружу идёт
    только имя этапа и подобранный шаг (анти-референс PRODUCT.md про «сырой
    машинный вывод»). Имя этапа экранируется: сообщение уходит с parse_mode=HTML.
    """
    from src.ux.html_text import esc

    return (
        f"❌ Обработка прервалась на этапе «{esc(stage_name)}».\n"
        f"{processing_failure_step(error_text)}"
    )


def resume_failure_message(error_text: str) -> str:
    """Сообщение о сбое возобновления: что случилось + следующий шаг.

    Шаг зависит от класса сбоя: при кончившихся кредитах и исчерпанной квоте
    перезапуск не поможет (это на нашей стороне), при временном сбое API —
    поможет через несколько минут, в остальных случаях — повторная отправка
    записи.
    """
    if is_quota_exhausted(error_text):
        return (
            "❌ Не получилось продолжить обработку: "
            "на сервисе закончился лимит обращений к модели.\n"
            "Это ограничение на нашей стороне, файл менять не нужно — "
            "отправьте запись позже."
        )

    if is_insufficient_credits(error_text):
        return (
            "❌ Не получилось продолжить обработку: "
            "на сервисе закончились ресурсы.\n"
            "Это временная проблема на нашей стороне, файл менять не нужно — "
            "отправьте запись снова позже."
        )

    if is_transient_api_error(error_text):
        return (
            "❌ Не получилось продолжить обработку: сервис не ответил.\n"
            "Похоже на временный сбой на стороне сервиса — попробуйте через несколько минут."
        )

    return (
        "❌ Не получилось продолжить обработку.\n"
        "Отправьте запись заново — обычно повторная попытка помогает."
    )
