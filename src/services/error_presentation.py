"""Как сбой обработки выглядит для пользователя.

Один источник правды для признака «кончились кредиты LLM» (HTTP 402) и текста,
которым о сбое сообщает путь возобновления после подтверждения сопоставления.

Раньше правила жили только в воркере очереди, а возобновление отправляло
``str(error)`` как есть — то есть сырой ответ провайдера. На проде 22.07.2026 это
означало payload OpenRouter с ``user_id`` и ``max_tokens`` прямо в чат, да ещё с
советом «начните обработку заново», бесполезным при кончившихся кредитах.

Текст сырой ошибки пользователю не показывается вовсе: к моменту возобновления
запись уже расшифрована, так что осмысленных для человека классов сбоя всего два
(кончились ресурсы / временный сбой API), а внутренности провайдера ему ничего не
объясняют — их место в логах, где теперь есть и traceback.

Голос — канон «что + шаг»: первая строка про то, что случилось, вторая про
следующий шаг. Без разметки: путь возобновления отправляет текст без
``parse_mode``, поэтому звёздочки и теги показались бы буквально.
"""


def is_insufficient_credits(error_text: str) -> bool:
    """Признак ошибки «закончились кредиты на LLM» (HTTP 402).

    Срабатывает и на типизированном ``LLMInsufficientCreditsError`` (русское
    «кредит»), и на сыром ответе провайдера (англ. «credits» / «402»).
    Регистр входа не важен.
    """
    lowered = (error_text or "").lower()
    return (
        "кредит" in lowered
        or "credit" in lowered
        or "error code: 402" in lowered
    )


def is_transient_api_error(error_text: str) -> bool:
    """Признак временного сбоя внешнего API — повтор через пару минут осмыслен."""
    lowered = (error_text or "").lower()
    return any(
        pattern in lowered
        for pattern in (
            'rate limit', 'quota', 'service unavailable',
            'connection', 'timeout', 'network',
        )
    )


def resume_failure_message(error_text: str) -> str:
    """Сообщение о сбое возобновления: что случилось + следующий шаг.

    Шаг зависит от класса сбоя: при кончившихся кредитах перезапуск не поможет
    (это на нашей стороне), при временном сбое API — поможет через несколько
    минут, в остальных случаях — повторная отправка записи.
    """
    if is_insufficient_credits(error_text):
        return (
            "❌ Не получилось продолжить обработку: "
            "на сервисе закончились ресурсы.\n"
            "Это временная проблема на нашей стороне, файл менять не нужно — "
            "отправьте запись снова позже."
        )

    if is_transient_api_error(error_text):
        return (
            "❌ Не получилось продолжить обработку: сервис не ответил.\n"
            "Похоже на временную проблему с API — попробуйте через несколько минут."
        )

    return (
        "❌ Не получилось продолжить обработку.\n"
        "Отправьте запись заново — обычно повторная попытка помогает."
    )
