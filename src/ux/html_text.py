"""Разметка Telegram HTML для поверхности сообщений (ADR-0005).

Один язык разметки на весь бот — Telegram HTML. Экранирование берём из
единственного канона ``protocol_render.telegram_html`` (не плодим копий таблицы);
здесь лишь тонкая обёртка ``esc`` для читаемой сборки ДИНАМИЧЕСКИХ подстановок
(имя шаблона/участника, имя файла, ввод пользователя) в HTML-сообщения.

Статические литералы разметки пишем прямо тегами (``<b>…</b>``, ``<i>…</i>``,
``<code>…</code>``); экранировать их не нужно. Экранируем только динамику.
"""

from src.services.protocol_render.telegram_html import escape_telegram_html


def esc(value: object) -> str:
    """Экранировать динамическую подстановку для parse_mode="HTML".

    Приводит значение к строке и пропускает через канон экранирования Telegram
    HTML (только «&», «<», «>»). Пустое/None становится пустой строкой.
    """
    if value is None:
        return ""
    return escape_telegram_html(str(value))
