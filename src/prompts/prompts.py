def build_generation_prompt(
    transcription: str,
    template_variables: Dict[str, str],
    speaker_mapping: Optional[Dict[str, str]] = None,
    meeting_type: str = "general",
    meeting_agenda: Optional[str] = None,
    project_list: Optional[str] = None,
    meeting_topic: Optional[str] = None,
    meeting_date: Optional[str] = None,
    meeting_time: Optional[str] = None,
    participants_list: Optional[str] = None,
) -> str:
    """
    Создает промпт для второго запроса (извлечение данных протокола).
    XML-tagged structure: context -> speakers -> fields -> rules -> transcription.

    Дата и время подписаны именами ``meeting_date``/``meeting_time``: по ним к
    ним обращаются правила полей ``date`` и ``time`` в системном промпте.

    ``participants_list`` — участники с ролями, как их дал пользователь: без них
    модель не знает промолчавших и не отличает руководителя от исполнителей.
    Спикеры, оставшиеся без имени, перечисляются явно — правило ответственного
    называет их «Участник N».
    """
    # Описаний у полей нет (правила — в системном промпте), поэтому только ключи:
    # раньше здесь стояли пустые «- key: »
    variables_str = "\n".join(
        f"- {key}: {desc}" if desc else f"- {key}" for key, desc in template_variables.items()
    )
    type_instructions = _get_type_specific_instructions(meeting_type)

    parts = [f"Извлеки данные из транскрипции для протокола. Тип встречи: {meeting_type}"]

    # Context (before transcription)
    context_parts = []
    if meeting_topic:
        context_parts.append(f"Тема встречи: {meeting_topic}")
    if meeting_date:
        context_parts.append(f"Дата встречи (meeting_date): {meeting_date}")
    if meeting_time:
        context_parts.append(f"Время встречи (meeting_time): {meeting_time}")
    if meeting_agenda:
        context_parts.append(f"Повестка встречи:\n{meeting_agenda}")
    if project_list:
        context_parts.append(f"Список проектов:\n{project_list}")
    if context_parts:
        parts.append(f"<context>\n{chr(10).join(context_parts)}\n</context>")

    # Speaker mapping. Метки есть в тексте — сопоставление привязывает реплики к
    # именам. Меток нет (запись истории до сохранения размеченного текста) —
    # привязать не к чему: имена идут только как участники.
    mapping = speaker_mapping or {}
    labels = list(dict.fromkeys(_SPEAKER_LABEL.findall(transcription)))
    labeled = bool(labels)
    if participants_list:
        parts.append(f"<participants>\n{participants_list}\n</participants>")
    if mapping and labeled:
        mapping_str = "\n".join([f"{k} = {v}" for k, v in mapping.items()])
        parts.append(f"<speakers>\n{mapping_str}\n</speakers>")
    elif mapping:
        names = "\n".join(dict.fromkeys(mapping.values()))
        if not participants_list:
            parts.append(f"<participants>\n{names}\n</participants>")
        parts.append(
            "В транскрипции нет меток спикеров: не приписывай реплики и "
            "обязательства конкретным людям — имена участников используй только "
            "для списка участников."
        )
    unnamed = [label for label in labels if label not in mapping]
    if unnamed:
        unnamed_str = "\n".join(
            f"{label} → Участник {label.split('_', 1)[1]}" for label in unnamed
        )
        parts.append(
            "Спикеры без имени — в протоколе (участники, обсуждение, "
            f"ответственные) называй их так:\n{unnamed_str}"
        )

    # Fields (rules are now in system prompt for caching)
    parts.append(f"<fields>\n{variables_str}\n</fields>")

    if type_instructions:
        parts.append(type_instructions.strip())

    # Transcription last (largest block)
    parts.append(f"<transcription>\n{transcription}\n</transcription>")

    parts.append("Верни только валидный JSON. Все значения — строки.")

    return "\n\n".join(parts)


_TASK_KEYS = ("decisions", "action_items", "tasks", "tasks_od")


def _context_and_priorities(keys) -> str:
    """Блоки КОНТЕКСТ и ПРИОРИТЕТ ПОЛЕЙ — только о полях этого шаблона.

    Раньше блоки называли discussion/decisions/tasks во всех шаблонах: в «Кратком
    резюме» нет discussion, tasks нет ни в одном брифе — модель получала
    приоритет поля, которого нет, и перекос объёма в соседние поля.
    """
    keys = set(keys)
    structure_target = "discussion" if "discussion" in keys else "протокол"
    lines = [
        "КОНТЕКСТ:",
        f"- Повестка встречи — структурируй {structure_target} по её пунктам",
        "- Список проектов — привязывай обсуждения к проектам",
    ]
    priorities = []
    if "discussion" in keys:
        priorities.append("- discussion — МАКСИМАЛЬНО подробное")
    task_keys = [key for key in _TASK_KEYS if key in keys]
    if task_keys:
        priorities.append(f"- {', '.join(task_keys)} — точные формулировки с ответственными")
    if "participants" in keys:
        priorities.append("- participants — полный список")
    if priorities:
        lines += ["", "ПРИОРИТЕТ ПОЛЕЙ:", *priorities]
    return "\n".join(lines)


def build_generation_system_prompt(
    template_variables: Optional[Dict[str, str]] = None,
    field_rules: Optional[Dict[str, str]] = None,
) -> str:
    """
    Системный промпт для второго запроса (извлечение данных).

    Field-specific rules are included in the system prompt (stable per template)
    so that OpenAI can cache the prefix and reduce token costs on repeated calls
    with the same template.

    ``field_rules`` (бриф-путь) — готовые {ключ: инструкция} в нужном порядке;
    когда задан, вытесняет вывод правил из ``template_variables`` (legacy-путь).
    """
    base = (
        "Ты — профессиональный протоколист. Извлекай данные из транскрипции "
        "и заполняй поля протокола.\n\n"

        "ФОРМАТ ВЫВОДА — СТРОГО ВАЛИДНЫЙ JSON:\n"
        "- ВСЕ значения — ПРОСТЫЕ СТРОКИ. НИКАКИХ объектов {} или массивов []\n"
        "- Маркированные списки: каждый пункт с новой строки с маркером '- '\n"
        "- Нумерованные списки (правило поля требует \"N. ...\"): каждый пункт "
        "с новой строки как '1. ', '2. ' — БЕЗ маркера '- ' перед номером\n"
        "- Если данных для поля нет — верни пустую строку \"\". Не придумывай текст-заглушку\n\n"

        "ПРИНЦИПЫ:\n"
        "- Используй ТОЛЬКО факты из транскрипции. НЕ домысливай\n"
        "- Обрабатывай ВСЮ транскрипцию равномерно — начало, середину и конец\n"
        "- Заменяй SPEAKER_N на реальные имена из сопоставления\n"
        "- Указывай КТО что сказал: 'Иван Петров: предложил...' (кроме образовательных "
        "встреч — там конспект материала без атрибуции реплик)\n"
        "- Явные фонетические искажения известных терминов от распознавания речи "
        "нормализуй к канону (например, «котовер» → cutover, «биг дата» → BigData, "
        "«сап» → SAP). Мусор, который не удаётся распознать, не выдавай за термин в "
        "кавычках. Ничего не выдумывай — правь только очевидные искажения\n"
        "- Букву «ё» используй последовательно во всём документе (отчёт, а не отчет); "
        "написание имён собственных не меняй\n\n"
    )

    keys = list(field_rules) if field_rules is not None else list(template_variables or {})
    base += _context_and_priorities(keys)

    if field_rules is not None:
        rules_text = "\n\n".join(rule for rule in field_rules.values() if rule)
    elif template_variables:
        rules_text = _build_field_specific_rules(template_variables)
    else:
        rules_text = ""

    if rules_text:
        base += f"\n\nПРАВИЛА ДЛЯ ПОЛЕЙ:\n{rules_text}"

    return base


